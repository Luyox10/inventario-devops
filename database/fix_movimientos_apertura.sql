-- =============================================================
-- Verificación: debe devolver 0 filas (o solo diferencias de ±1
-- por redondeo si hay movimientos concurrentes)
-- =============================================================
SELECT
  p.id, p.nombre, p.sku, p.stock_actual,
  COALESCE(SUM(CASE WHEN m.tipo='ENTRADA' THEN m.cantidad ELSE -m.cantidad END), 0) AS stock_por_movimientos,
  p.stock_actual - COALESCE(SUM(CASE WHEN m.tipo='ENTRADA' THEN m.cantidad ELSE -m.cantidad END), 0) AS diferencia
FROM productos p
LEFT JOIN movimientos m ON m.producto_id = p.id
WHERE p.activo = 1
GROUP BY p.id, p.nombre, p.sku, p.stock_actual
HAVING diferencia <> 0
ORDER BY diferencia DESC;
